window.LANG_TAGS = { en: 'en', id: 'id', zh: 'zh-Hans' };

/* Look up a string for the current language, falling back to English. */
window.tr = function (k) {
  var d = window.I18N[window.CP_LANG] || window.I18N.en;
  return d[k] != null ? d[k] : window.I18N.en[k];
};

window.applyLang = function (lang) {
  if (!window.I18N[lang]) lang = 'en';
  var d = window.I18N[lang], en = window.I18N.en;
  /* A key missing from a language falls back to English, then to the page's own markup
     (which is the English text for long passages), kept so switching back restores it. */
  function pick(el, key, attr, read) {
    if (el[attr] === undefined) el[attr] = read();
    if (lang !== 'en' && d[key] != null) return d[key];
    return en[key] != null ? en[key] : el[attr];
  }
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = pick(el, el.dataset.i18n, '_i18nText', function () { return el.textContent; });
  });
  document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
    el.innerHTML = pick(el, el.dataset.i18nHtml, '_i18nHtml', function () { return el.innerHTML; });
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
    el.placeholder = pick(el, el.dataset.i18nPh, '_i18nPh', function () { return el.placeholder; });
  });
  document.documentElement.lang = window.LANG_TAGS[lang];
  try { localStorage.setItem('cp-lang', lang); } catch (e) {}
  document.querySelectorAll('.lang button').forEach(function (b) {
    b.classList.toggle('on', b.dataset.lang === lang);
  });
  window.CP_LANG = lang;
  if (typeof window.onLangChange === 'function') window.onLangChange(lang);
};

window.initLang = function () {
  var saved = 'en';
  try { saved = localStorage.getItem('cp-lang') || 'en'; } catch (e) {}
  document.querySelectorAll('.lang button').forEach(function (b) {
    b.addEventListener('click', function () { window.applyLang(b.dataset.lang); });
  });
  window.applyLang(saved);
};
